const POSITION_FALLBACK = { GK: gk, DEF: def0, DF: def0, MIL: mid, MID: mid, MF: mid, ATT: att, FW: att, ST: att };

// deterministic hash from a player id (string or number)
const hashId = (id) => {
  const s = String(id ?? '');
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h;
};

// Buckets approximatifs sur le pool de 120 portraits :
// young (U21) : indices 0–39 — visages plutôt jeunes
// prime (22–29) : indices 30–95 — la majorité du pool
// vet (30+) : indices 80–119 — visages plus marqués
const BUCKETS = {
  young: { start: 0, size: 40 },
  prime: { start: 30, size: 66 },
  vet:   { start: 80, size: 40 },
};

const bucketFor = (age) => {
  if (!age && age !== 0) return BUCKETS.prime;
  if (age <= 21) return BUCKETS.young;
  if (age >= 30) return BUCKETS.vet;
  return BUCKETS.prime;
};

export const getPlayerPortrait = (positionOrPlayer) => {
  // Backward compatibility: called with just position string
  if (typeof positionOrPlayer === 'string') {
    return POSITION_FALLBACK[positionOrPlayer.toUpperCase()] ?? POOL[0];
  }
  const player = positionOrPlayer ?? {};
  if (player.id != null && OVERRIDES[player.id]) {
    return OVERRIDES[player.id];
  }
  if (player.id != null) {
    const bucket = bucketFor(player.age);
    const idx = bucket.start + (hashId(player.id) % bucket.size);
    return POOL[idx % POOL.length];
  }
  return POSITION_FALLBACK[String(player.position || '').toUpperCase()] ?? POOL[0];
};

export const getPortraitForPlayer = getPlayerPortrait;
