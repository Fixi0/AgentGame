const slugify = (s) => String(s ?? '')
  .toLowerCase()
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .replace(/[^a-z0-9]+/g, '_')
  .replace(/^_+|_+$/g, '');

export const CLUBS = RAW_CLUBS.map((club) => ({
  ...club,
  id: club.id ?? `club_${club.countryCode.toLowerCase()}_${slugify(club.name)}`,
}));

export const getCountry = (countryCode) => COUNTRIES.find((country) => country.code === countryCode) ?? COUNTRIES[0];

export const getUnlockedCountries = (reputation) =>
  COUNTRIES.filter((country) => reputation >= country.minReputation);

export const getCitiesForCountry = (countryCode) =>
  [...new Set(CLUBS.filter((club) => club.countryCode === countryCode).map((club) => club.city))].sort();
